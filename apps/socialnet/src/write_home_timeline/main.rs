//! Async Rust port of the C++ Write-Home-Timeline Service.
//!
//! This application listens to a RabbitMQ queue for new posts, fetches the
//! author's followers from a social graph gRPC service, and then writes the post
//! into the Redis-based home timeline for each follower.
//!
//! It uses the Tokio runtime for async operations, `lapin` for RabbitMQ,
//! `redis-rs` for Redis, `bb8` for connection pooling, and `tonic` for gRPC.

use anyhow::{Context, Result};
use std::sync::Arc;
use tokio::task::JoinHandle;
use tracing::{error, info, Level};
use tracing_subscriber::FmtSubscriber;

use crate::worker::run_worker;

